import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import { marked } from 'marked';

import markedKatex from 'marked-katex-extension';

marked.use(markedKatex({
  throwOnError: false,
  output: 'html',
}));

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = path.join(root, 'content', 'blog');
const outputFile = path.join(root, 'src', 'app', 'blog-posts.generated.ts');

const easternDate = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/New_York', month: 'short', day: 'numeric', year: 'numeric',
});
const easternTime = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/New_York', hour: 'numeric', minute: '2-digit', timeZoneName: 'short',
});
const easternYearMonth = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/New_York', year: 'numeric', month: 'numeric',
});

function requiredString(value, key, filename) {
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`${filename}: frontmatter '${key}' must be a nonempty string`);
  }
  return value.trim();
}

function plainTextFromHtml(html) {
  // Previews are plain text; the full post keeps Markdown formatting.
  return html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&#(x[\da-f]+|\d+);/gi, (_, entity) => {
      const codepoint = entity[0].toLowerCase() === 'x'
        ? parseInt(entity.slice(1), 16) : parseInt(entity, 10);
      return Number.isFinite(codepoint) && codepoint <= 0x10ffff && !(codepoint >= 0xd800 && codepoint <= 0xdfff)
        ? String.fromCodePoint(codepoint) : ' ';
    })
    .replace(/&(?:amp|lt|gt|quot|apos|nbsp|#39);/gi, (entity) => ({
      '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"',
      '&apos;': "'", '&nbsp;': ' ', '&#39;': "'",
    })[entity.toLowerCase()] ?? entity)
    .replace(/\s+/g, ' ')
    .trim();
}

function previewFromHtml(html) {
  const words = plainTextFromHtml(html).split(/\s+/).filter(Boolean);
  return words.slice(0, 150).join(' ') + (words.length > 150 ? '…' : '');
}

async function main() {
  await mkdir(contentDir, { recursive: true });
  const filenames = (await readdir(contentDir)).filter((file) => file.endsWith('.md')).sort();
  const posts = [];
  const seenSlugs = new Set();

  for (const filename of filenames) {
    const slug = filename.slice(0, -3);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
      throw new Error(`${filename}: use lowercase, hyphen-separated filenames`);
    }
    if (seenSlugs.has(slug)) throw new Error(`Duplicate blog slug: ${slug}`);
    seenSlugs.add(slug);

    const source = await readFile(path.join(contentDir, filename), 'utf8');
    const { data, content } = matter(source);
    if (data.draft === true) continue;

    const title = requiredString(data.title, 'title', filename);
    const category = requiredString(data.category, 'category', filename);
    const dateText = data.date instanceof Date ? data.date.toISOString() : requiredString(data.date, 'date', filename);
    if (!/T\d{2}:\d{2}(?::\d{2}(?:\.\d+)?)?(?:Z|[+-]\d{2}:\d{2})$/.test(dateText)) {
      throw new Error(`${filename}: date must be an ISO timestamp with a timezone, e.g. 2026-10-22T18:30:00-04:00`);
    }
    const parsedDate = new Date(dateText);
    if (Number.isNaN(parsedDate.getTime())) throw new Error(`${filename}: invalid date`);

    const dateParts = easternYearMonth.formatToParts(parsedDate);
    const year = Number(dateParts.find((part) => part.type === 'year')?.value);
    const month = Number(dateParts.find((part) => part.type === 'month')?.value);
    const html = await marked.parse(content, { gfm: true, breaks: false });
    posts.push({
      slug, title, category, date: parsedDate.toISOString(), year, month,
      dateLabel: `${easternDate.format(parsedDate)} @ ${easternTime.format(parsedDate)}`,
      excerpt: previewFromHtml(html), html,
    });
  }

  posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
  const code = `// Generated by scripts/generate-blog-index.mjs. Do not edit directly.\n` +
    `export interface BlogPost {\n` +
    `  slug: string; title: string; category: string; date: string;\n` +
    `  year: number; month: number; dateLabel: string; excerpt: string; html: string;\n` +
    `}\n` +
    `export const BLOG_POSTS: readonly BlogPost[] = ${JSON.stringify(posts, null, 2)};\n`;
  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, code, 'utf8');
  console.log(`Blog index: ${posts.length} published post(s) -> src/app/blog-posts.generated.ts`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
